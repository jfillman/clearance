//go:generate go run ../../tools/contract -o ../../contract/clearance-core.json

// ContractVersion is the contract's info.version: bumped by hand on a breaking change to a route.
const ContractVersion = "1.0.0"

// ContractPath is the committed contract, relative to the module root.
const ContractPath = "contract/clearance-core.json"

// Contract is the OpenAPI 3.1 document of the core's HTTP API, generated from the route table (Routes) and, by
// reflection, the Go request and response types: a struct's JSON-tagged fields, the strictness of request bodies
// (additionalProperties false; required from a `contract:"required"` tag) and the always-present fields of
// responses (required: no omitempty).
func Contract() ([]byte, error) {
	g := &schemaGen{defs: map[string]any{}, strict: map[reflect.Type]bool{}}
	// Request types first: a type reachable from a request body is decoded strictly wherever it appears.
	for _, rt := range Routes() {
		if rt.Request != nil {
			g.markStrict(reflect.TypeOf(rt.Request))
		}
	}
	paths := map[string]any{}
	for _, rt := range Routes() {
		op := map[string]any{"operationId": rt.OperationID, "summary": rt.Summary,
			"x-clearance-auth": rt.Auth, "x-clearance-max-body": rt.MaxBody}
		switch rt.Auth {
		case AuthBearer, AuthProvider:
			op["security"] = []any{map[string]any{"bearer": []any{}}}
		default:
			op["security"] = []any{}
		}
		var params []any
		for _, seg := range strings.Split(rt.Path, "/") {
			if strings.HasPrefix(seg, "{") {
				params = append(params, map[string]any{"name": strings.Trim(seg, "{}"), "in": "path", "required": true,
					"schema": map[string]any{"type": "string"}})
			}
		}
		if params != nil {
			op["parameters"] = params
		}
		switch {
		case rt.Request != nil:
			op["requestBody"] = map[string]any{"required": true, "content": map[string]any{
				"application/json": map[string]any{"schema": g.schema(reflect.TypeOf(rt.Request))}}}
		case rt.RequestNote != "":
			op["requestBody"] = map[string]any{"required": rt.Method == "POST" && rt.RequestNote != `{"reason": string}`,
				"content": map[string]any{"application/json": map[string]any{
					"schema": map[string]any{"type": "object", "description": rt.RequestNote}}}}
		}
		resps := map[string]any{}
		for _, r := range rt.Responses {
			resp := map[string]any{"description": r.Description}
			if r.Body != nil {
				resp["content"] = map[string]any{"application/json": map[string]any{"schema": g.schema(reflect.TypeOf(r.Body))}}
			}
			resps[strconv.Itoa(r.Status)] = resp
		}
		op["responses"] = resps
		item, _ := paths[rt.Path].(map[string]any)
		if item == nil {
			item = map[string]any{}
			paths[rt.Path] = item
		}
		item[strings.ToLower(rt.Method)] = op
	}
	if g.err != nil {
		return nil, g.err
	}
	doc := map[string]any{
		"openapi": "3.1.0",
		"info": map[string]any{"title": "Clearance core", "version": ContractVersion,
			"description": "The Go core's HTTP API (internal/server). Generated by tools/contract from the route table " +
				"and the Go types; do not edit. Decision ids are evidence seqs; CLEARANCE_PROVIDERS registers the " +
				"providers that may evaluate and record."},
		"paths": paths,
		"components": map[string]any{
			"schemas":         g.defs,
			"securitySchemes": map[string]any{"bearer": map[string]any{"type": "http", "scheme": "bearer"}},
		},
		"x-clearance-record-kinds": RecordKinds,
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

type schemaGen struct {
	defs   map[string]any
	strict map[reflect.Type]bool
	err    error
}

var (
	tTime      = reflect.TypeOf(time.Time{})
	tPyTime    = reflect.TypeOf(gate.PyTime{})
	tInt       = reflect.TypeOf(decide.Int{})
	tNumber    = reflect.TypeOf(json.Number(""))
	tRaw       = reflect.TypeOf(json.RawMessage(nil))
	tDecided   = reflect.TypeOf(gate.Decided{})
	tMarshaler = reflect.TypeOf((*json.Marshaler)(nil)).Elem()
)

// special are the types whose JSON is not their Go shape.
func (g *schemaGen) special(t reflect.Type) (map[string]any, bool) {
	switch t {
	case tTime:
		return map[string]any{"type": "string", "format": "date-time"}, true
	case tPyTime:
		return map[string]any{"type": "string", "description": "Python datetime.isoformat() of an aware time"}, true
	case tInt:
		return map[string]any{"type": "integer", "description": "exact at any size"}, true
	case tNumber:
		return map[string]any{"type": "number"}, true
	case tRaw:
		return map[string]any{}, true
	case tDecided:
		return map[string]any{"allOf": []any{g.schema(reflect.TypeOf(gate.Change{})),
			map[string]any{"type": "object", "properties": map[string]any{"audit_seq": map[string]any{"type": "integer"}},
				"required": []any{"audit_seq"}}}}, true
	}
	return nil, false
}

func (g *schemaGen) markStrict(t reflect.Type) {
	for t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice || t.Kind() == reflect.Map {
		t = t.Elem()
	}
	if t.Kind() != reflect.Struct || g.strict[t] {
		return
	}
	if _, sp := g.special(t); sp {
		return
	}
	g.strict[t] = true
	for i := 0; i < t.NumField(); i++ {
		if f := t.Field(i); f.IsExported() {
			g.markStrict(f.Type)
		}
	}
}

func defName(t reflect.Type) string {
	pkg := t.PkgPath()
	if i := strings.LastIndex(pkg, "/"); i >= 0 {
		pkg = pkg[i+1:]
	}
	if pkg == "server" {
		return t.Name()
	}
	return strings.ToUpper(pkg[:1]) + pkg[1:] + t.Name()
}

func (g *schemaGen) schema(t reflect.Type) map[string]any {
	if s, ok := g.special(t); ok {
		return s
	}
	switch t.Kind() {
	case reflect.Pointer:
		inner := g.schema(t.Elem())
		if typ, ok := inner["type"].(string); ok && len(inner) == 1 {
			return map[string]any{"type": []any{typ, "null"}}
		}
		return map[string]any{"oneOf": []any{inner, map[string]any{"type": "null"}}}
	case reflect.String:
		return map[string]any{"type": "string"}
	case reflect.Bool:
		return map[string]any{"type": "boolean"}
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return map[string]any{"type": "integer"}
	case reflect.Float32, reflect.Float64:
		return map[string]any{"type": "number"}
	case reflect.Interface:
		return map[string]any{}
	case reflect.Slice, reflect.Array:
		return map[string]any{"type": "array", "items": g.schema(t.Elem())}
	case reflect.Map:
		return map[string]any{"type": "object", "additionalProperties": g.schema(t.Elem())}
	case reflect.Struct:
		name := defName(t)
		ref := map[string]any{"$ref": "#/components/schemas/" + name}
		if _, done := g.defs[name]; done {
			return ref
		}
		if t.Implements(tMarshaler) || reflect.PointerTo(t).Implements(tMarshaler) {
			g.fail(fmt.Errorf("contract: %s has its own MarshalJSON: describe it in schemaGen.special", t))
			return ref
		}
		g.defs[name] = map[string]any{} // a placeholder for recursion
		props := map[string]any{}
		var required []string
		g.fields(t, props, &required)
		def := map[string]any{"type": "object", "properties": props}
		if g.strict[t] {
			def["additionalProperties"] = false
		}
		if len(required) > 0 {
			sort.Strings(required)
			def["required"] = required
		}
		g.defs[name] = def
		return ref
	}
	g.fail(fmt.Errorf("contract: no schema for %s", t))
	return map[string]any{}
}

// fields adds t's JSON fields (embedded structs flattened, as encoding/json does).
func (g *schemaGen) fields(t reflect.Type, props map[string]any, required *[]string) {
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if !f.IsExported() {
			continue
		}
		tag := f.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if f.Anonymous && name == "" {
			et := f.Type
			if et.Kind() == reflect.Pointer {
				et = et.Elem()
			}
			g.fields(et, props, required)
			continue
		}
		if name == "" {
			g.fail(fmt.Errorf("contract: %s.%s has no json tag", t, f.Name))
			continue
		}
		props[name] = g.schema(f.Type)
		omit := strings.Contains(opts, "omitempty")
		if g.strict[t] {
			if f.Tag.Get("contract") == "required" {
				*required = append(*required, name)
			}
		} else if !omit {
			*required = append(*required, name)
		}
	}
}

func (g *schemaGen) fail(err error) {
	if g.err == nil {
		g.err = err
	}
}
