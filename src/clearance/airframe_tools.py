def _strip(s: Any, n: int = 300) -> Any:
    return s[:n] if isinstance(s, str) else s


def find_kind(name: str, contract: dict = CONTRACT) -> tuple[dict | None, dict | None]:
    """A kind's sidecar and XRD summary by Kind, lowercase key or plural (airframe-verify's find_kind)."""
    every = {**contract["components"], **contract.get("targets", {}), **contract.get("kinds", {})}
    low = name.lower()
    for key, sc in every.items():
        xrd = contract["xrds"].get(sc["kind"]) or {}
        if low in (key, sc["kind"].lower(), (xrd.get("plural") or "").lower()):
            return sc, xrd
    return None, None


def _answer(rule: str, message: str, hint: str) -> dict:
    """A refusal about the question, not the caller (no such app, kind or XR): data the agent acts on."""
    return {"error": {"rule": rule, "message": message, "hint": hint}}


