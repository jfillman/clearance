class AirframeTools:
    def __init__(self, kube, validator=None, registry: airframe_plan.Registry | None = None,
                 contract: dict = CONTRACT, cluster: str | None = None, argo_namespace: str = ARGO_NAMESPACE,
                 workers: int = 8):
        self.kube, self.validator, self.registry = kube, validator, registry
        self.contract, self.cluster, self.argo_ns, self.workers = contract, cluster, argo_namespace, workers

    # contract ---------------------------------------------------------------------------------------------------
    def capabilities(self, kind: str | None = None, section: str | None = None) -> Any:
        c = self.contract
        if kind:
            sc, xrd = find_kind(kind, c)
            if sc is None:
                return _answer("AF-KIND-404", f"no Airframe kind {kind!r}", "Call airframe.capabilities with no arguments for the list.")
            return {"kind": sc["kind"], "xrd": xrd, **sc}
        if section:
            return {section: c[section] if section != "chart" else c["chart"]}
        every = {**c["components"], **c.get("targets", {}), **c.get("kinds", {})}
        return {"contract": c["$schema"], "source": "airframe contract/airframe-contract.json (vendored)",
                "chart": {"name": c["chart"]["name"], "fields": {k: {kk: vv for kk, vv in v.items() if kk != "default"}
                                                                 for k, v in c["chart"]["fields"].items()}},
                "kinds": [{"kind": sc["kind"], "role": sc.get("role"), "summary": sc.get("summary"),
                           "apiVersion": (c["xrds"].get(sc["kind"]) or {}).get("apiVersion"),
                           "plural": (c["xrds"].get(sc["kind"]) or {}).get("plural"),
                           "outputs": sorted(sc.get("outputs") or {}),
                           "verify": [v["id"] for v in sc.get("verify") or []]}
                          for _, sc in sorted(every.items())],
                "more": "airframe.capabilities {kind} for one kind's outputs, conditions and verify checks; "
                        "{section: chart|xrds|components|targets|kinds} for a whole section"}

    def explain(self, rule: str) -> Any:
        if rule in AF_RULES:
            return {"rule": rule, **AF_RULES[rule], "source": "airframe tools/airframe-validate"}
        every = {**self.contract["components"], **self.contract.get("targets", {}), **self.contract.get("kinds", {})}
        found = []
        for sc in every.values():
            for k in sc.get("knownFailures") or []:
                if k["id"] == rule:
                    found.append({"kind": sc["kind"], "knownFailure": rule, "condition": k["condition"],
                                  "description": k["meaning"], "hint": k["hint"]})
            for c in sc.get("conditions") or []:
                for r in c.get("reasons") or []:
                    if r["reason"] == rule:
                        found.append({"kind": sc["kind"], "condition": c["type"], "status": r["status"], "description": r["meaning"]})
        for k in GENERIC_FAILURES:
            if k["id"] == rule:
                found.append({"kind": "*", "knownFailure": rule, "condition": k["condition"], "description": k["meaning"], "hint": k["hint"]})
        if found:
            return {"rule": rule, "matches": found, "source": "airframe contract/airframe-contract.json"}
        return _answer("AF-EXPLAIN-404", f"{rule!r} is not an AF-* rule, a condition reason or a knownFailures id Airframe declares",
                       "AF-* rules: " + ", ".join(sorted(AF_RULES)))

    # validator --------------------------------------------------------------------------------------------------
    def validate(self, documents: list[dict], app: str | None, mode: str = "values", render: bool = True) -> Any:
        if self.validator is None:
            raise AirframeError("no airframe-validate command is configured")
        results = self.validator.run(documents, app, mode, render)
        files = []
        for d, res in zip(documents, results):
            files.append({"path": d["path"], "valid": bool(res.get("valid")),
                          "problems": [{"pointer": p.get("loc"), "rule": p.get("rule"), "message": p.get("message"),
                                        "hint": p.get("hint"), "severity": "error"} for p in res.get("problems") or []],
                          "warnings": [{"pointer": p.get("loc"), "rule": p.get("rule"), "message": p.get("message"),
                                        "hint": p.get("hint"), "severity": "warning"} for p in res.get("warnings") or []]})
        return {"valid": all(f["valid"] for f in files), "mode": mode, "files": files}

    # planner ----------------------------------------------------------------------------------------------------
    def plan(self, spec: dict, base_cicd: Any = None) -> Any:
        if self.registry is None:
            raise AirframeError("no cluster registry is configured for the planner")
        if isinstance(base_cicd, str):
            try:
                base_cicd = yaml.safe_load(base_cicd)
            except yaml.YAMLError:
                return _answer("AF-SPEC-002", "baseCicd does not parse as YAML", "Pass the app's cicd.yaml as it is, or as a mapping.")
            if not isinstance(base_cicd, dict):
                return _answer("AF-SPEC-002", "baseCicd is not a YAML mapping", "Pass the app's cicd.yaml as it is, or as a mapping.")
        try:
            cs = airframe_plan.plan(spec, self.registry, base_cicd=base_cicd)
        except airframe_plan.NeedsInput as e:
            return {"needsInput": {"question": e.question, "options": e.options}}
        except airframe_plan.SpecError as e:
            return _answer("AF-SPEC-001", str(e), "Fix the AppSpec at the path named; airframe.capabilities lists the chart's fields.")
        return dataclasses.asdict(cs)

    # cluster state ----------------------------------------------------------------------------------------------
    def _xrs_in(self, namespace: str) -> list[dict]:
        plurals = sorted({x["plural"] for x in self.contract["xrds"].values() if x.get("group") == "catalog.hangar.io"})
        with ThreadPoolExecutor(self.workers) as ex:
            lists = list(ex.map(lambda p: self.kube.list(xr_path(p, namespace)), plurals))
        return sorted((o for lst in lists for o in lst), key=lambda o: (o.get("kind", ""), o["metadata"]["name"]))

    def _cicd(self, app: str) -> tuple[str, str, list[dict]] | None:
        for t in TYPES:
            ns = f"{t}-{app}-cicd"
            xrs = self._xrs_in(ns)
            if xrs:
                return t, ns, xrs
        return None

    def _no_app(self, app: str) -> dict:
        return _answer("AF-APP-404", f"no Airframe XRs for {app!r} in " + " or ".join(f"{t}-{app}-cicd" for t in TYPES),
                       "Check the app name; an app exists once its tenants-repo XR request is synced.")

    def _env_xrs(self, app: str, env: str | None) -> tuple[str, str, list[dict], list[dict], list[dict]] | None:
        found = self._cicd(app)
        if found is None:
            return None
        t, cicd_ns, cicd = found
        flight = [x for x in cicd if x.get("kind") == "ApplicationEnvironment" and (x.get("spec") or {}).get("env") == env]
        keep = [x for x in cicd if x.get("kind") != "ApplicationEnvironment" or env is None or x in flight]
        env_xrs = self._xrs_in(f"{t}-{app}-{env}") if env else []
        return t, cicd_ns, keep, env_xrs, flight

    def status(self, app: str, env: str | None = None) -> Any:
        found = self._env_xrs(app, env)
        if found is None:
            return self._no_app(app)
        t, cicd_ns, cicd, env_xrs, flight = found
        xrs = [normalise(x, self.contract) for x in cicd + env_xrs]
        out = {"app": app, "env": env, "namespaces": {"cicd": cicd_ns, **({"env": f"{t}-{app}-{env}"} if env else {})},
               "xrs": xrs,
               "summary": {"xrs": len(xrs), "ready": sum(x["ready"] for x in xrs),
                           "notReady": [f"{x['kind']}/{x['name']}" for x in xrs if not x["ready"]],
                           "stale": [f"{x['kind']}/{x['name']}" for x in xrs if x["stale"]]}}
        if env and not env_xrs and not flight:
            out["notes"] = [f"no XRs in {t}-{app}-{env} on this cluster and no ApplicationEnvironment for {env!r}"]
        return out

    def _applications(self, app: str, env: str, t: str) -> list[dict]:
        sel = f"hangar.io/app={app},hangar.io/env={env}"
        apps = []
        for ns in dict.fromkeys([self.argo_ns, f"{t}-{app}-cicd"]):   # Ground in argocd-apps, ephemeral in -cicd
            apps += self.kube.list(argo_path("applications", ns), label_selector=sel)
        return apps

    @staticmethod
    def _app_summary(a: dict) -> dict:
        st, sp = a.get("status") or {}, a.get("spec") or {}
        sync = st.get("sync") or {}
        sources = sp.get("sources") or ([sp["source"]] if sp.get("source") else [])
        revs = sync.get("revisions") or ([sync["revision"]] if sync.get("revision") else [])
        op = st.get("operationState") or {}
        return {"name": a["metadata"]["name"], "namespace": a["metadata"]["namespace"], "project": sp.get("project"),
                "destination": sp.get("destination"),
                "sync": {"status": sync.get("status"),
                         "revisions": [{"repoURL": s.get("repoURL"), "path": s.get("path"), "targetRevision": s.get("targetRevision"),
                                        "revision": revs[i] if i < len(revs) else None} for i, s in enumerate(sources)]},
                "health": {"status": (st.get("health") or {}).get("status"), "message": _strip((st.get("health") or {}).get("message"))},
                "operation": {"phase": op.get("phase"), "message": _strip(op.get("message")), "finishedAt": op.get("finishedAt")},
                "reconciledAt": st.get("reconciledAt")}

    @staticmethod
    def _rollout_summary(r: dict) -> dict:
        st, sp, md = r.get("status") or {}, r.get("spec") or {}, r.get("metadata") or {}
        containers = (((sp.get("template") or {}).get("spec") or {}).get("containers")) or []
        obs = st.get("observedGeneration")
        try:
            obs = int(obs) if obs is not None else None      # Argo Rollouts writes it as a string
        except ValueError:
            obs = None
        return {"name": md.get("name"), "namespace": md.get("namespace"), "phase": st.get("phase"), "message": _strip(st.get("message")),
                "replicas": sp.get("replicas"), "readyReplicas": st.get("readyReplicas"), "availableReplicas": st.get("availableReplicas"),
                "updatedReplicas": st.get("updatedReplicas"), "images": [c.get("image") for c in containers],
                "strategy": next(iter(sp.get("strategy") or {}), None), "currentStepIndex": st.get("currentStepIndex"),
                "stableRS": st.get("stableRS"), "currentPodHash": st.get("currentPodHash"),
                "generation": md.get("generation"), "observedGeneration": obs,
                "stale": (obs < md["generation"]) if (obs is not None and md.get("generation") is not None) else None}

    def describe(self, app: str, env: str) -> Any:
        found = self._env_xrs(app, env)
        if found is None:
            return self._no_app(app)
        t, cicd_ns, cicd, env_xrs, flight = found
        env_ns = f"{t}-{app}-{env}"
        xrs = []
        for x in cicd + env_xrs:
            n = normalise(x, self.contract)
            xrs.append({"kind": n["kind"], "name": n["name"], "namespace": n["namespace"], **_spec_summary(x),
                        "ready": n["ready"], "synced": n["synced"], "stale": n["stale"], "notTrue": n["notTrue"]})
        notes: list[str] = []
        apps = self._applications(app, env, t)
        tier = "flight" if flight else ("ephemeral" if any((a["metadata"].get("labels") or {}).get("hangar.io/ephemeral-env") == "true"
                                                         for a in apps) else "ground")
        rollouts: list[dict] = []
        for a in apps:
            for res in (a.get("status") or {}).get("resources") or []:
                if res.get("kind") == "Rollout" and res.get("group") == "argoproj.io":
                    r = self.kube.get(argo_path("rollouts", res["namespace"], res["name"]))
                    if r is not None:
                        rollouts.append(self._rollout_summary(r))
        if not apps:
            for f in flight:
                cl = (f.get("spec") or {}).get("cluster")
                if cl and cl != self.cluster:
                    notes.append(f"{env} is a Flight environment on {cl}: its Application and Rollout run there, and this "
                                 f"adapter reads {self.cluster or 'one cluster'} only")
            if not flight:
                rollouts = [self._rollout_summary(r) for r in self.kube.list(argo_path("rollouts", env_ns))]
                notes.append(f"no Argo CD Application labelled hangar.io/app={app}, hangar.io/env={env} in "
                             f"{self.argo_ns} or {cicd_ns}")
        return {"app": app, "env": env, "tier": tier, "namespaces": {"cicd": cicd_ns, "env": env_ns}, "xrs": xrs,
                "applications": [self._app_summary(a) for a in apps], "rollouts": rollouts, **({"notes": notes} if notes else {})}

    def verify(self, app: str, kind: str, name: str, env: str | None = None) -> Any:
        sc, xrd = find_kind(kind, self.contract)
        if sc is None or not xrd:
            return _answer("AF-KIND-404", f"no verify contract for kind {kind!r}", "airframe.capabilities lists every kind with its verify checks.")
        xr = None
        for t in TYPES:
            ns = f"{t}-{app}-{env}" if env else f"{t}-{app}-cicd"
            xr = self.kube.get(xr_path(xrd["plural"], ns, name))
            if xr is not None:
                break
        if xr is None:
            where = " or ".join(f"{t}-{app}-{env or 'cicd'}" for t in TYPES)
            return _answer("AF-XR-404", f"no {sc['kind']} {name!r} in {where}",
                           "airframe.status lists the app's XRs; a Ground environment's components are in <type>-<app>-<env>.")
        steps = [check_synced(sc, xr)]
        for step in sc.get("verify") or []:
            run = step["run"]
            res = {"id": step["id"], "kind": run["kind"], "check": step["check"]}
            if not when_matches(step.get("when"), xr):
                res.update(status="skipped", reason=f"when {step['when']} does not match this XR")
            elif run["kind"] == "manual":
                res.update(status="manual", reason="no tool can make this check; the sentence says what a human looks at")
            elif run["kind"] in ("condition", "xrField"):
                try:
                    res.update(status="pass", detail=(_run_condition if run["kind"] == "condition" else _run_xr_field)(run, xr))
                except StepFailed as e:
                    res.update(status="fail", detail=str(e))
            elif run["kind"] == "resource":
                res.update(self._resource_step(run, xr))
            else:
                where, names = _where(run, xr)
                res.update(status="skipped", reason=_SKIP_REASON[run["kind"]].format(where=where), names=names)
            steps.append(res)
        counts = {s: sum(1 for x in steps if x["status"] == s) for s in ("pass", "fail", "skipped", "manual")}
        return {"kind": sc["kind"], "namespace": xr["metadata"]["namespace"], "name": name,
                "passed": counts["fail"] == 0, "counts": counts, "steps": steps}

    def _resource_step(self, run: dict, xr: dict) -> dict:
        """A `resource` step is made only when the resource is one Clearance may read at all (an XR, an Application or
        a Rollout); otherwise it is skipped, never attempted."""
        plural, _, group = run["resource"].partition(".")
        try:
            name = render(run["name"], xr)
            ns = render(run.get("namespace", "{namespace}"), xr)
        except Unresolved as e:
            return {"status": "fail", "detail": f"cannot resolve {{{e.args[0]}}}: the XR has not published it"}
        if group == "catalog.hangar.io" and not run.get("clusterScoped"):
            path = xr_path(plural, ns, name)
        elif group == "argoproj.io" and plural in ("applications", "rollouts") and not run.get("clusterScoped"):
            path = argo_path(plural, ns, name)
        else:
            return {"status": "skipped", "names": {"resource": run["resource"], "name": name},
                    "reason": f"reads {run['resource']} {name}, which is outside Clearance's read allowlist "
                              "(Airframe XRs, Argo CD Applications and Rollouts)"}
        obj = self.kube.get(path)
        if obj is None:
            return {"status": "fail", "detail": f"{run['resource']} {name} does not exist"}
        parts = [f"{run['resource']} {name} exists"]
        if run.get("condition"):
            c = next((c for c in _conditions(obj) if c.get("type") == run["condition"]["type"]), None)
            if c is None or c.get("status") != run["condition"].get("status", "True"):
                return {"status": "fail", "detail": f"{run['resource']} {name}: {run['condition']['type']} is {c.get('status') if c else 'absent'}"}
            parts.append(f"{c['type']}={c['status']}")
        if run.get("field"):
            v = dig(obj, run["field"])
            if "equals" in run and v != run["equals"]:
                return {"status": "fail", "detail": f"{run['resource']} {name}: {run['field']} is {v!r}, expected {run['equals']!r}"}
            parts.append(f"{run['field']}={v!r}")
        return {"status": "pass", "detail": ", ".join(parts)}


