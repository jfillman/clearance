class MemoryKube:
    """The KubeReader interface over a dict of objects, with the same allowlist, so the tools' own tests cannot reach a
    path the real adapter would refuse. Records every path asked for."""

    ARGO = {"Application": "applications", "Rollout": "rollouts"}

    def __init__(self, objects: list[dict] | None = None, contract: dict = CONTRACT):
        self.plurals = {k: v["plural"] for k, v in contract["xrds"].items()}
        self.objects: dict[str, dict] = {}
        self.paths: list[str] = []
        for o in objects or []:
            self.add(o)

    def add(self, obj: dict) -> None:
        md = obj["metadata"]
        kind = obj["kind"]
        if kind in self.ARGO:
            path = argo_path(self.ARGO[kind], md["namespace"], md["name"])
        else:
            path = xr_path(self.plurals[kind], md["namespace"], md["name"])
        self.objects[path] = obj

    def get(self, path: str, query: dict | None = None) -> Any:
        if not path_allowed(path):
            raise PathRefused(path)
        self.paths.append(path)
        return copy.deepcopy(self.objects.get(path))

    def list(self, path: str, label_selector: str | None = None) -> list[dict]:
        if not path_allowed(path):
            raise PathRefused(path)
        self.paths.append(path)
        want = dict(kv.split("=", 1) for kv in label_selector.split(",")) if label_selector else {}
        out = []
        for p, o in sorted(self.objects.items()):
            if p.rsplit("/", 1)[0] == path:
                labels = o["metadata"].get("labels") or {}
                if all(labels.get(k) == v for k, v in want.items()):
                    out.append(copy.deepcopy(o))
        return out


# --- normalising XR state -------------------------------------------------------------------------------------------

def _reason_meaning(sc: dict | None, ctype: str, reason: str | None) -> str | None:
    for c in (sc or {}).get("conditions") or []:
        if c.get("type") == ctype:
            for r in c.get("reasons") or []:
                if r.get("reason") == reason:
                    return r.get("meaning")
    return None


def _known_failure(sc: dict | None, ctype: str, message: str) -> dict | None:
    for k in ((sc or {}).get("knownFailures") or []) + GENERIC_FAILURES:
        if k.get("condition") == ctype and re.search(k["match"], message or ""):
            return k
    return None


def _conditions(xr: dict) -> list[dict]:
    return [c for c in (xr.get("status") or {}).get("conditions") or [] if isinstance(c, dict)]


def normalise(xr: dict, contract: dict = CONTRACT) -> dict:
    """One XR's conditions as the agent needs them. Each condition: its reason, what that reason means (the kind's
    closed reason set in the bundle), a hint when it is not True, and observedGeneration against the XR's
    generation. Crossplane stamps observedGeneration on Synced and Ready; a composition function's own conditions
    (ComponentReady, CicdOnboarded) carry none, but they are written in the reconcile Synced records, so they inherit
    Synced's when Synced is True, and are of unknown freshness (stale: null) when it is not."""
    md = xr.get("metadata") or {}
    sc, _ = find_kind(xr.get("kind", ""), contract)
    gen = md.get("generation")
    conds = _conditions(xr)
    synced = next((c for c in conds if c.get("type") == "Synced"), None)
    synced_obs = synced.get("observedGeneration") if synced and synced.get("status") == "True" else None
    out = []
    for c in conds:
        ctype, status, reason, msg = c.get("type"), c.get("status"), c.get("reason"), c.get("message") or ""
        obs, source = c.get("observedGeneration"), "condition"
        if obs is None and synced_obs is not None and ctype not in ("Synced", "Ready"):
            obs, source = synced_obs, "Synced"
        n = {"type": ctype, "status": status, "reason": reason, "message": _strip(msg),
             "observedGeneration": obs, "stale": (obs < gen) if (obs is not None and gen is not None) else None}
        if source != "condition":
            n["observedGenerationFrom"] = source
        meaning = _reason_meaning(sc, ctype, reason)
        if meaning:
            n["meaning"] = meaning
        if status != "True":
            k = _known_failure(sc, ctype, msg)
            if k:
                n["knownFailure"], n["hint"] = k["id"], f"{k['meaning']} {k['hint']}"
            elif meaning:
                n["hint"] = meaning
            elif ctype == "Ready":
                n["hint"] = "A composed resource is not ready yet: see the kind's own conditions and this message."
            elif ctype == "Synced":
                n["hint"] = "Crossplane could not reconcile the XR with its current spec; the message says why."
            else:
                n["hint"] = "Not a reason the Airframe contract lists for this kind; read the message."
        out.append(n)
    stale = [n["type"] for n in out if n["stale"]]
    return {"kind": xr.get("kind"), "name": md.get("name"), "namespace": md.get("namespace"), "generation": gen,
            "ready": any(c["type"] == "Ready" and c["status"] == "True" for c in out),
            "synced": any(c["type"] == "Synced" and c["status"] == "True" for c in out),
            "stale": bool(stale), "staleConditions": stale,
            "notTrue": [c["type"] for c in out if c["status"] != "True"], "conditions": out}


def _spec_summary(xr: dict) -> dict:
    spec = copy.deepcopy(xr.get("spec") or {})
    refs = (spec.pop("crossplane", None) or {}).get("resourceRefs") or []
    return {"spec": spec, "composedResources": len(refs)}


# --- verify step runners: mirror airframe-verify's for the kinds an XR alone can answer -----------------------------

class StepFailed(Exception):
    pass


def _run_condition(run: dict, xr: dict) -> str:
    want = run.get("status", "True")
    c = next((c for c in _conditions(xr) if c.get("type") == run["type"]), None)
    if c is None:
        raise StepFailed(f"the XR has no {run['type']} condition")
    detail = f"{run['type']}={c.get('status')} reason={c.get('reason')}"
    gen, obs = (xr.get("metadata") or {}).get("generation"), c.get("observedGeneration")
    if gen is not None and obs is not None and obs < gen:
        detail += f" (observedGeneration {obs} < generation {gen}: not yet reconciled against the current spec)"
    if c.get("status") != want or (run.get("reasons") and c.get("reason") not in run["reasons"]):
        raise StepFailed(detail + (f"; message: {_strip(c.get('message'))}" if c.get("message") else ""))
    return detail


def _run_xr_field(run: dict, xr: dict) -> str:
    v = dig(xr, run["path"])
    ok = (v == run["equals"]) if "equals" in run else (v in run["in"])
    if not ok:
        raise StepFailed(f"{run['path']} is {v!r}, expected {run.get('equals', run.get('in'))!r}")
    return f"{run['path']}={v!r}"


def check_synced(sc: dict, xr: dict) -> dict:
    """airframe-verify's implicit first step: Synced=False means the kind's own conditions may be stale."""
    res = {"id": "xr-synced", "kind": "condition", "check": "The XR is Synced: Crossplane reconciled it with the current spec."}
    c = next((c for c in _conditions(xr) if c.get("type") == "Synced"), None)
    if c is None:
        return {**res, "status": "fail", "detail": "the XR has no Synced condition yet"}
    if c.get("status") == "True":
        return {**res, "status": "pass", "detail": "Synced=True"}
    msg = c.get("message") or ""
    k = _known_failure(sc, "Synced", msg)
    if k:
        return {**res, "status": "fail", "knownFailure": k["id"],
                "detail": f"Synced=False, known failure {k['id']}: {k['meaning']} Hint: {k['hint']}"}
    return {**res, "status": "fail", "detail": f"Synced=False ({c.get('reason')}): {msg[:300]}"}


def _where(run: dict, xr: dict) -> tuple[str, dict]:
    """The names a skipped step would have used, rendered from the XR (connection-detail names, never values)."""
    def r(tpl):
        try:
            return render(tpl, xr)
        except Unresolved as e:
            return f"<{e.args[0]} not published>"
    ns = r(run.get("namespace", "{namespace}"))
    k = run["kind"]
    if k in ("secretKeys", "oauthClientCredentials"):
        names = {"secret": r(run["secret"]), "namespace": ns, **({"keys": run["keys"]} if "keys" in run else {})}
        return f"{ns}/{names['secret']}", names
    if k == "configMapKeys":
        return f"{ns}/{r(run['configMap'])}", {"configMap": r(run["configMap"]), "namespace": ns, "keys": run["keys"]}
    if k == "tcp":
        return f"{r(run['service'])}:{run['port']} in {ns}", {"service": r(run["service"]), "port": run["port"], "namespace": ns}
    if k == "http":
        target = r(run["url"]) if run.get("url") else f"svc/{r(run['service'])}:{run['port']}{run.get('path', '/')} in {ns}"
        return target, {"target": target}
    if k == "cloudCli":
        return run["cli"], {"cli": run["cli"]}
    return "", {}


