"""The airframe.* tools: Airframe's contract, validator and planner, and read-only cluster state, for agents.

All seven are T0. Self-contained on purpose (a later split moves Hangar backends out of the clearance package):
Clearance's core knows them only by their registration (tiers.py, dispatch.py) and the per-app scope rule (R023).

  capabilities  the contract bundle, airframe's contract/airframe-contract.json, vendored as
                schemas/airframe-contract.json and drift-tested against airframe main
  validate      airframe's own tools/airframe-validate, run as a configured command or container on the proposed
                content, parsed from its --format json (never reimplemented here)
  explain       an AF-* rule id (AF_RULES: the bundle carries no rules yet, so the table is here, with a drift test
                that it names exactly the ids airframe-validate can emit), a condition reason or a knownFailures id
  plan          airframe_plan.plan, the AppSpec planner
  status        an app's or one environment's XR conditions: reason, hint, observedGeneration against generation
  describe      one environment: its XRs, the Argo CD Application syncing it, its Rollout
  verify        an XR's sidecar verify checks (xrds/<kind>.meta.yaml `verify:`) from the XR alone; a step that needs a
                Secret value, a ConfigMap, a port-forward, exec or a cloud CLI is `skipped` with the reason

Where things are, from airframe and glidepath (not guessed): an app's XR and its TektonCICD, SecretStores and
Flight ApplicationEnvironments (`<app>-<cluster>-<env>`) live in `<type>-<app>-cicd`; a Ground environment's
component XRs and workload in `<type>-<app>-<env>` (type `app`, or `infra` for an InfraService; glidepath-app's
envNamespace). A Ground environment's Application is generated by glidepath-app's lower-envs ApplicationSet into
argocd-apps, an ephemeral one's into `<type>-<app>-cicd`, both labelled hangar.io/app and hangar.io/env; the
Rollout is the one in the Application's status.resources. A Flight environment's Application and Rollout run on
its own cluster, which this adapter does not read; describe says so instead of guessing.
"""
