class ValidatorCommand:
    """airframe-validate as a configured argv: the script from an airframe checkout (needs python3, pyyaml, jsonschema
    and helm), or a container of airframe's tools/validate.Containerfile image. No shell; the content is written to a
    temporary directory and the files are passed as arguments. For a container, `{dir}` in argv is replaced by that
    directory and `mount` is where it appears inside, e.g.
        ValidatorCommand(["podman", "run", "--rm", "--network=none", "-v", "{dir}:/work:ro", IMAGE], mount="/work")"""

    def __init__(self, argv: list[str], mount: str | None = None, timeout: float = 120.0):
        self.argv, self.mount, self.timeout = list(argv), mount, timeout

    def run(self, documents: list[dict], app: str | None, mode: str, render: bool) -> list[dict]:
        with tempfile.TemporaryDirectory(prefix="airframe-validate-") as td:
            files = []
            for i, d in enumerate(documents):
                name = posixpath.basename(d["path"])     # the name matters (a *.release.yaml is a release file)
                (Path(td) / str(i)).mkdir()
                (Path(td) / str(i) / name).write_text(d["content"])
                files.append(f"{self.mount or td}/{i}/{name}")
            argv = [a.replace("{dir}", td) for a in self.argv] + ["--format", "json"]
            argv += ["--xr"] if mode == "xr" else (["--app", app] if app else []) + ([] if render else ["--no-render"])
            try:
                r = subprocess.run(argv + files, capture_output=True, text=True, timeout=self.timeout)  # noqa: S603 - argv is configuration
            except (OSError, subprocess.TimeoutExpired) as e:
                raise AirframeError(f"airframe-validate did not run: {type(e).__name__}") from e
        if r.returncode not in (0, 1):
            raise AirframeError(f"airframe-validate exited {r.returncode}")
        try:
            out = json.loads(r.stdout)
        except ValueError as e:
            raise AirframeError("airframe-validate printed no JSON") from e
        if not isinstance(out, list) or len(out) != len(documents):
            raise AirframeError("airframe-validate returned an unexpected shape")
        return out


class FakeValidator:
    """Tests: answers in airframe-validate's --format json shape. A document whose content contains `bogusKey:` gets an
    AF-SCHEMA-001, one containing `ghp_` an AF-SECRET-001; everything else is valid."""

    def __init__(self):
        self.calls: list[tuple] = []

    def run(self, documents, app, mode, render):
        self.calls.append((tuple(d["path"] for d in documents), app, mode, render))
        out = []
        for i, d in enumerate(documents):
            problems = []
            if "bogusKey:" in d["content"]:
                problems.append({"loc": "/bogusKey", "rule": "AF-SCHEMA-001", "message": "unknown key 'bogusKey'",
                                 "hint": "no such field; see values.schema.json"})
            if "ghp_" in d["content"]:
                problems.append({"loc": "/env/0/value", "rule": "AF-SECRET-001", "message": "looks like a GitHub token",
                                 "hint": "secrets are references, never literal values"})
            out.append({"file": f"/tmp/x/{i}/{posixpath.basename(d['path'])}", "valid": not problems,
                        "problems": problems, "warnings": []})
        return out


